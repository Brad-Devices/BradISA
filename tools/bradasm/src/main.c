/* bradasm -- command line driver for the BradISA V2 assembler.
 *
 * Reads an assembly file, writes a flat little-endian binary image, a
 * Verilog boot-ROM include, or a one-'%08X'-word-per-line memory image
 * ($readmemh / textio).  The assembler core is bradasm.c; this file only
 * knows how to get bytes on and off disk.
 */

#include "brad/bradasm.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static const char *progname = "bradasm";

static void usage(FILE *f)
{
    fprintf(f,
        "usage: %s [options] <source.s>\n"
        "\n"
        "  -o FILE     write the binary image here (default: a.bin)\n"
        "  -V FILE     write a Verilog boot-ROM include here instead\n"
        "  -m FILE     write one '%%08X' hex word per line (what testbenches\n"
        "              $readmemh / textio-load from the assembler's output)\n"
        "  -S          print symbols and exit without writing an image\n"
        "  -q          quiet: no output on success\n"
        "  -h          this help\n"
        "\n"
        "bradasm assembles BradISA V2. It emits 32-bit instructions only:\n"
        "the shipped core has no compressed decode path, so C.* forms are\n"
        "rejected rather than silently mistranslated.\n",
        progname);
}

/* Read a whole file into memory.  Caller frees. */
static char *read_file(const char *path)
{
    FILE *f = fopen(path, "rb");
    long n;
    char *buf;

    if (f == NULL) {
        fprintf(stderr, "%s: cannot open %s\n", progname, path);
        return NULL;
    }
    if (fseek(f, 0, SEEK_END) != 0) {
        fclose(f);
        fprintf(stderr, "%s: %s is not seekable\n", progname, path);
        return NULL;
    }
    n = ftell(f);
    if (n < 0) {
        fclose(f);
        fprintf(stderr, "%s: cannot size %s\n", progname, path);
        return NULL;
    }
    rewind(f);

    buf = (char *)malloc((size_t)n + 1u);
    if (buf == NULL) {
        fclose(f);
        fprintf(stderr, "%s: out of memory\n", progname);
        return NULL;
    }
    if (n > 0 && fread(buf, 1, (size_t)n, f) != (size_t)n) {
        fprintf(stderr, "%s: short read on %s\n", progname, path);
        free(buf);
        fclose(f);
        return NULL;
    }
    buf[n] = '\0';
    fclose(f);
    return buf;
}

/* Emit the image as a Verilog include for an RTL file that owns an
 * instruction memory called `imem`.  This is how the Tang Nano 9K boot ROM
 * reaches the board top without anyone hand-writing a hex literal again.
 *
 * It is emitted as an `initial begin` assignment block, not a packed localparam
 * array: every simulator and synthesizer this tree uses (iverilog, yosys,
 * verilator) accepts initial-block ROM fills, while unpacked-array assignment
 * patterns are a SystemVerilog feature that iverilog still declines. */
static int write_verilog(const char *path, const char *stem,
                         const struct brad_as_output *out, int quiet)
{
    FILE *f = fopen(path, "w");
    unsigned i;
    unsigned words = out->count;

    if (f == NULL) {
        fprintf(stderr, "%s: cannot write %s\n", progname, path);
        return 1;
    }
    fprintf(f, "// Generated by bradasm from %s -- do not edit.\n", stem);
    fprintf(f, "// %u word%s at 0x%08x (word i = address 4*i, from image origin 0).\n",
            words, words == 1 ? "" : "s", 0u);
    fprintf(f, "initial begin\n");
    for (i = 0; i < words; i++)
        fprintf(f, "    imem[%u] = 32'h%08x;\n", i, out->code[i]);
    fprintf(f, "end\n");
    if (fclose(f) != 0) {
        fprintf(stderr, "%s: short write on %s\n", progname, path);
        return 1;
    }
    if (!quiet)
        printf("%s: %u word%s -> %s\n", progname, words, words == 1 ? "" : "s",
               path);
    return 0;
}

/* One uppercase-hex word per line, in address order: the memory-image format
 * iverilog's $readmemh and GHDL's textio/read both speak natively.  The
 * whole point is that a testbench which loads this file executes precisely
 * the words bradasm produced, no hand-encoded literals anywhere. */
static int write_mem(const char *path, const struct brad_as_output *out,
                     int quiet)
{
    FILE *f = fopen(path, "w");
    unsigned i;

    if (f == NULL) {
        fprintf(stderr, "%s: cannot write %s\n", progname, path);
        return 1;
    }
    for (i = 0; i < out->count; i++)
        fprintf(f, "%08x\n", out->code[i]);
    if (fclose(f) != 0) {
        fprintf(stderr, "%s: short write on %s\n", progname, path);
        return 1;
    }
    if (!quiet)
        printf("%s: %u word%s -> %s\n", progname, out->count,
               out->count == 1 ? "" : "s", path);
    return 0;
}

/* Flat little-endian binary image of the words, in address order --
 * what a real bus download would carry. */
static int write_bin(const char *path, const struct brad_as_output *out,
                     int quiet)
{
    FILE *f = fopen(path, "wb");
    unsigned i;

    if (f == NULL) {
        fprintf(stderr, "%s: cannot write %s\n", progname, path);
        return 1;
    }
    for (i = 0; i < out->count; i++) {
        unsigned char b[4];
        b[0] = (unsigned char)(out->code[i] & 0xFF);
        b[1] = (unsigned char)((out->code[i] >> 8) & 0xFF);
        b[2] = (unsigned char)((out->code[i] >> 16) & 0xFF);
        b[3] = (unsigned char)((out->code[i] >> 24) & 0xFF);
        if (fwrite(b, 1, 4, f) != 4) {
            fprintf(stderr, "%s: short write on %s\n", progname, path);
            fclose(f);
            return 1;
        }
    }
    if (fclose(f) != 0) {
        fprintf(stderr, "%s: short write on %s\n", progname, path);
        return 1;
    }
    if (!quiet)
        printf("%s: %u word%s -> %s\n", progname, out->count,
               out->count == 1 ? "" : "s", path);
    return 0;
}

static void print_symbols(const struct brad_as_output *out)
{
    unsigned i;

    printf("; %u symbol%s\n", out->nsymbols,
           out->nsymbols == 1 ? "" : "s");
    for (i = 0; i < out->nsymbols; i++)
        printf("%-24s 0x%08x\n", out->symbols[i].name, out->symbols[i].addr);
    printf("entry 0x%08x\n", out->entry_point);
}

int main(int argc, char **argv)
{
    const char *inpath = NULL;
    const char *outpath = "a.bin";
    const char *vlogpath = NULL;
    const char *mempath = NULL;
    char *src;
    struct brad_as_output out;
    int do_syms = 0, quiet = 0, syms_only = 0;
    int i, rc = 0;

    if (argc > 0 && argv[0] && *argv[0])
        progname = argv[0];

    for (i = 1; i < argc; i++) {
        const char *a = argv[i];
        if (a[0] == '-' && a[1] != '\0') {
            switch (a[1]) {
            case 'o': outpath = argv[++i]; break;
            case 'V': vlogpath = argv[++i]; break;
            case 'm': mempath = argv[++i]; break;
            case 'S': syms_only = 1; break;
            case 's': do_syms = 1; break;
            case 'q': quiet = 1; break;
            case 'h': usage(stdout); return 0;
            default:
                fprintf(stderr, "%s: unknown option '%s'\n", progname, a);
                fprintf(stderr, "%s: try -h\n", progname);
                return 2;
            }
        } else if (inpath == NULL) {
            inpath = a;
        } else {
            fprintf(stderr, "%s: one source file at a time('%s' unused)\n",
                    progname, a);
            return 2;
        }
    }

    if (inpath == NULL) {
        usage(stderr);
        return 2;
    }

    src = read_file(inpath);
    if (src == NULL)
        return 1;

    memset(&out, 0, sizeof out);
    if (brad_as_assemble(src, &out) != 0 || !out.ok) {
        fprintf(stderr, "%s: %s: line %d: %s\n", progname, inpath,
                out.error.line, out.error.msg);
        free(src);
        return 1;
    }

    if (syms_only)
        print_symbols(&out);
    else {
        if (vlogpath != NULL)
            rc |= write_verilog(vlogpath, inpath, &out, quiet);
        else if (mempath != NULL)
            rc = write_mem(mempath, &out, quiet);
        else
            rc = write_bin(outpath, &out, quiet);
        if (do_syms)
            print_symbols(&out);
    }

    free(src);
    return rc;
}
